// Package scaleway_test pins the Scaleway catalog adapter: the target contract in
// internal/adapter/target/targettest, the snapshot header the catalog reports, a
// golden change detector for the parsed catalog, the declared EU regions, and
// that a cancelled run reads nothing. The snapshot document format itself, its
// strictness and its errors are pinned once, in the shared reader's own tests
// (internal/adapter/target/snapshot). It is black-box: only the package's
// exported API is used.
